// Bundles lib/site/render/entry.tsx (with its own copy of React) into one plain module,
// lib/site/render/renderer.gen.js, so the website designs can be saved as standalone HTML
// from the Cloudflare worker and the browser preview alike. Runs before every build.
import { build } from 'esbuild';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
await build({
  entryPoints: [join(root, 'lib/site/render/entry.tsx')],
  outfile: join(root, 'lib/site/render/renderer.gen.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  jsx: 'automatic',
  minify: true,
  legalComments: 'none',
  loader: { '.css': 'text', '.js': 'js' },
  plugins: [{
    name: 'runtime-as-text',
    setup(b) { b.onLoad({ filter: /render[\\/]runtime\.js$/ }, async (a) => ({ contents: (await import('node:fs')).readFileSync(a.path, 'utf8'), loader: 'text' })); },
  }],
  define: { 'process.env.NODE_ENV': '"production"', 'process.env.NEXT_PUBLIC_LIVE': '"false"' },
  banner: { js: '// Generated by scripts/build-renderer.mjs. Do not edit.\n// @ts-nocheck\n/* eslint-disable */' },
  logLevel: 'warning',
});
console.log('Renderer written to lib/site/render/renderer.gen.js');
